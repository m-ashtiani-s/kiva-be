"""
Turns Iran's province and city lists into the Flyway migration V11__geo.sql.

    python tools/geo/geo_to_sql.py          (from the repository root)

provinces.json and cities.json are copies of taban-be/assets, kept here so it is clear where the SQL came from.
The SQL file is generated once and committed; the application never reads these JSON files.
The fixes are the ones of PURCHASE_ROADMAP.md, section 5.1. The script refuses to write anything when the result
breaks one of the checks at the end.
"""
import collections
import json
import pathlib
import re

HERE = pathlib.Path(__file__).parent
OUTPUT = HERE.parent.parent / "src" / "main" / "resources" / "db" / "migration" / "V11__geo.sql"

# A space missing after «و» ("and") in a compound name: «سیستان وبلوچستان». Fixed only for these ids,
# because «چاه ورز» is a real name.
GLUED_AND_PROVINCES = {9, 16, 23}
GLUED_AND_CITIES = {23, 300, 1090}

# 364-367 are the postal districts of Tabriz (تبریز1- to تبریز4-), not cities; the shopper picks «تبریز» (361).
# 1217 is a second «گلوگاه» in Mazandaran; 1216 stays.
DROPPED_CITIES = {364, 365, 366, 367, 1217}

EXPECTED_PROVINCES = 31
EXPECTED_CITIES = 1319
MAX_NAME_LENGTH = 50


def fix_glued_and(name):
    return re.sub(r" و(?=\S)", " و ", name)


def fix_abad(name):
    """«اباد» as a word of its own becomes «آباد», like Tehran's «حسن آباد». Joined names (مهاباد، گناباد) stay."""
    return re.sub(r"(?<!\S)اباد(?!\S)", "آباد", name)


def load(file_name):
    with open(HERE / file_name, encoding="utf-8") as file:
        return json.load(file)


def provinces_of(rows):
    return [
        {"id": row["id"], "name": fix_glued_and(row["name"]) if row["id"] in GLUED_AND_PROVINCES else row["name"]}
        for row in rows
    ]


def cities_of(rows):
    cities = []
    position_in_province = collections.Counter()
    for row in rows:
        if row["id"] in DROPPED_CITIES:
            continue
        name = fix_glued_and(row["name"]) if row["id"] in GLUED_AND_CITIES else row["name"]
        position_in_province[row["provinceId"]] += 1
        cities.append({
            "id": row["id"],
            "provinceId": row["provinceId"],
            "name": fix_abad(name),
            "sortOrder": position_in_province[row["provinceId"]],
        })
    return cities


def check(provinces, cities):
    assert len(provinces) == EXPECTED_PROVINCES, f"{len(provinces)} provinces"
    assert len(cities) == EXPECTED_CITIES, f"{len(cities)} cities"
    province_ids = {p["id"] for p in provinces}
    assert len(province_ids) == len(provinces), "a province id twice"
    assert len({p["name"] for p in provinces}) == len(provinces), "a province name twice"
    assert len({c["id"] for c in cities}) == len(cities), "a city id twice"
    assert all(c["provinceId"] in province_ids for c in cities), "a city of an unknown province"
    names = collections.Counter((c["provinceId"], c["name"]) for c in cities)
    assert not [k for k, n in names.items() if n > 1], f"the same city name twice in a province: {names.most_common(3)}"
    for name in [p["name"] for p in provinces] + [c["name"] for c in cities]:
        assert name == name.strip() and "  " not in name, f"stray spaces in '{name}'"
        assert len(name) <= MAX_NAME_LENGTH, f"'{name}' is longer than {MAX_NAME_LENGTH}"
        assert not re.search(r"[0-9۰-۹]", name), f"digits in '{name}'"
        assert not re.search(r"(?<!\S)اباد(?!\S)", name), f"«اباد» without «آ» in '{name}'"
    fixed = [p for p in provinces if p["id"] in GLUED_AND_PROVINCES] + [c for c in cities if c["id"] in GLUED_AND_CITIES]
    assert all(not re.search(r" و\S", row["name"]) for row in fixed), "a «و» still glued"


def sql_text(text):
    return "'" + text.replace("'", "''") + "'"


SCHEMA = """\
-- Iran's provinces and cities, for addresses: GET /geo/provinces, the address book and checkout.
--
-- GENERATED by tools/geo/geo_to_sql.py from tools/geo/provinces.json and cities.json: change the script, not this file.
--
-- Reference data in plain tables, written only by migrations. The ids are the source file's ids (cities from 1 to
-- 1518, with gaps) and never change, because saved addresses point at them. sortOrder is the file's order, which is
-- Persian alphabetical order (چ after ت, گ after ک); a city's counts inside its province.
-- Fixed from the source (PURCHASE_ROADMAP.md, section 5.1): a missing space after «و» in six names, «اباد» as a word
-- of its own written «آباد», Tabriz's four postal districts and a second «گلوگاه» left out. 31 provinces, 1319 cities.

CREATE TABLE province_tbl
(
    "pId"        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "provinceId" INTEGER     NOT NULL UNIQUE CHECK ("provinceId" > 0),
    name         VARCHAR(50) NOT NULL UNIQUE CHECK (btrim(name) <> ''),
    "sortOrder"  INTEGER     NOT NULL
);

CREATE TABLE city_tbl
(
    "pId"        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "cityId"     INTEGER     NOT NULL UNIQUE CHECK ("cityId" > 0),
    "provinceId" INTEGER     NOT NULL REFERENCES province_tbl ("provinceId"),
    name         VARCHAR(50) NOT NULL CHECK (btrim(name) <> ''),
    "sortOrder"  INTEGER     NOT NULL,
    -- A city is chosen inside its province. Addresses point at this pair (V13), so the database itself keeps
    -- "the city belongs to the province"; it is also the index of a province's city list.
    CONSTRAINT city_tbl_province_city_key UNIQUE ("provinceId", "cityId"),
    -- Two cities of one province with the same name could not be told apart in a dropdown.
    CONSTRAINT city_tbl_province_name_key UNIQUE ("provinceId", name)
);
"""


def migration(provinces, cities):
    province_rows = ",\n".join(
        f"       ({p['id']}, {sql_text(p['name'])}, {position})" for position, p in enumerate(provinces, start=1)
    )
    city_rows = ",\n".join(
        f"       ({c['id']}, {c['provinceId']}, {sql_text(c['name'])}, {c['sortOrder']})" for c in cities
    )
    return (
        SCHEMA
        + '\nINSERT INTO province_tbl ("provinceId", name, "sortOrder")\nVALUES '
        + province_rows.lstrip()
        + ";\n"
        + '\nINSERT INTO city_tbl ("cityId", "provinceId", name, "sortOrder")\nVALUES '
        + city_rows.lstrip()
        + ";\n"
    )


def main():
    provinces = provinces_of(load("provinces.json"))
    cities = cities_of(load("cities.json"))
    check(provinces, cities)
    OUTPUT.write_text(migration(provinces, cities), encoding="utf-8", newline="\n")
    print(f"{OUTPUT.name}: {len(provinces)} provinces, {len(cities)} cities")


if __name__ == "__main__":
    main()
