-- Deleting an account (completion roadmap, phase 14, section 19.4).
--
-- The user's row is not deleted: orders, refunds, returns and reviews point at its id, and the orders are records for
-- the books. It is left as a tombstone instead: "deletedOn" set, the phone and every personal column emptied, CUSTOMER
-- only (User.erase). A tombstone has no phone, and a phone is there exactly while the account isn't deleted. The UNIQUE
-- key on phone allows any number of NULLs in PostgreSQL, so a deleted account's phone is free: logging in with it makes
-- a new account with a new id, unrelated to the old orders.
ALTER TABLE user_tbl
    ADD COLUMN "deletedOn" TIMESTAMPTZ,
    ALTER COLUMN phone DROP NOT NULL,
    ADD CONSTRAINT user_deleted_phone_check CHECK (("deletedOn" IS NULL) = (phone IS NOT NULL));

-- Why customers leave (DELETE /me's optional reason, decision 11): the text and when, and nothing that leads back to
-- the person. No user id, no order, no IP.
CREATE TABLE accountdeletionreason_tbl
(
    "pId"       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reason      VARCHAR(300) NOT NULL CHECK (btrim(reason) <> ''),
    "createdOn" TIMESTAMPTZ  NOT NULL
);
