-- The panel's change log (completion phase 1, step 1.1, roadmap section 5.1): who did what to what, and every field
-- from what to what. One row per successful panel write (a media upload aside), written by the use case in its own
-- transaction, so it is rolled back with the work it records. Reads and the system's own jobs are not logged.
--
-- A plain table. Rows are only ever inserted: a trigger refuses every UPDATE, and refuses every DELETE of a row younger
-- than 90 days, so the nightly retention job is the only thing that can remove one, and not even a bug in it can remove
-- a fresh one. "actorId" has no foreign key on purpose: the log stays after an account is deleted, and the actor's name
-- and phone are read from user_tbl when the log is read, never stored here.

CREATE TABLE auditlog_tbl
(
    "pId"         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "at"          TIMESTAMPTZ  NOT NULL,
    "actorId"     BIGINT       NOT NULL CHECK ("actorId" > 0),
    action        VARCHAR(60)  NOT NULL CHECK (action ~ '^[A-Z][A-Z0-9_]*$'),
    -- The contract's AuditEntityType; a new value of the contract is a new migration.
    "entityType"  VARCHAR(30)  NOT NULL CHECK ("entityType" IN ('PRODUCT', 'VARIANT', 'INVENTORY', 'MEDIA', 'CATEGORY',
                                                                'COLOR', 'MATERIAL', 'ORDER', 'RETURN', 'REFUND',
                                                                'DISCOUNT_CODE', 'CAMPAIGN', 'BANNER', 'ANNOUNCEMENT',
                                                                'TESTIMONIAL', 'FAQ', 'PAGE', 'SETTINGS', 'REVIEW',
                                                                'CONTACT_MESSAGE', 'USER')),
    -- An id or a code: 12, KV-218340, lilac, terms, shop.
    "entityId"    VARCHAR(64)  NOT NULL CHECK (length("entityId") > 0),
    -- The thing's name as it was at the moment of the change.
    "entityLabel" VARCHAR(200),
    -- [{field, from, to}], or null for an action with no "from what to what" (a delete).
    changes       JSONB CHECK (changes IS NULL OR jsonb_typeof(changes) = 'array'),
    -- IPv6 text is at most 45 characters.
    ip            VARCHAR(45),
    "traceId"     VARCHAR(64)
);

CREATE INDEX auditlog_at_idx ON auditlog_tbl ("at" DESC, "pId" DESC);
CREATE INDEX auditlog_entity_idx ON auditlog_tbl ("entityType", "entityId", "at" DESC);
CREATE INDEX auditlog_actor_idx ON auditlog_tbl ("actorId", "at" DESC);

CREATE FUNCTION auditlog_guard() RETURNS trigger AS
$$
BEGIN
    IF TG_OP = 'UPDATE' THEN
        RAISE EXCEPTION 'auditlog_tbl rows are never changed';
    END IF;
    -- DELETE: only the nightly retention job, and only rows past the 90 days
    IF OLD."at" >= now() - INTERVAL '90 days' THEN
        RAISE EXCEPTION 'auditlog_tbl rows younger than 90 days are never removed';
    END IF;
    RETURN OLD;
END
$$ LANGUAGE plpgsql;

CREATE TRIGGER auditlog_guard
    BEFORE UPDATE OR DELETE
    ON auditlog_tbl
    FOR EACH ROW
EXECUTE FUNCTION auditlog_guard();
