-- Idempotency keys (purchase step 11): one row per request done with an Idempotency-Key header (POST /orders and the
-- two payment retries). Written in the same transaction as the work, last; a failure that rolls back leaves none, so
-- its repeat runs again. A repeat with the same key and the same request answers from "outcome" (the ids of what was
-- made), never doing the work twice; the same key with another request is 409.
--
-- Two requests with one key at the same moment are kept apart by a transaction-level advisory lock on (customer,
-- scope, key), taken before this table is read; the unique key below is the last wall. Rows live 24 hours (the
-- cleanup job, step 16).

CREATE TABLE idempotencykey_tbl
(
    "pId"         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- A key belongs to its customer, and goes with the account.
    "userId"      BIGINT      NOT NULL REFERENCES user_tbl ("pId") ON DELETE CASCADE,
    scope         VARCHAR(20) NOT NULL CHECK (scope IN ('PLACE_ORDER', 'RETRY_PAYMENT', 'PAY_ORDER')),
    key           UUID        NOT NULL,
    -- SHA-256 of the request's canonical form (body and path): the same key with another one is another request.
    "requestHash" BYTEA       NOT NULL CHECK (length("requestHash") = 32),
    -- What the request made, by id: {"orderCode": "KV-218340", "paymentId": "pay_..."}.
    outcome       JSONB       NOT NULL CHECK (jsonb_typeof(outcome) = 'object'),
    "createdOn"   TIMESTAMPTZ NOT NULL,
    CONSTRAINT idempotencykey_tbl_key UNIQUE ("userId", scope, key)
);

-- The cleanup job removes the keys older than a day, oldest first.
CREATE INDEX idempotencykey_created_idx ON idempotencykey_tbl ("createdOn");
