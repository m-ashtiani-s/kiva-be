-- One-time codes, and the security log.
--
-- otpchallenge_tbl: every code sent, short-lived. Never the code itself, only its HMAC (salted, keyed with a pepper
-- kept outside the database). The send limits are counted from these rows, so they survive a restart.
--
-- securityevent_tbl: logins, wrong codes, token theft, role changes. Append-only: a trigger refuses every UPDATE and
-- DELETE, so not even a bug can rewrite what happened. "userId" has no foreign key on purpose: the events stay after
-- an account is deleted. The phone is kept whole, to see which number is under attack; logs only ever get it masked.

CREATE TABLE otpchallenge_tbl
(
    "pId"             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purpose           VARCHAR(30) NOT NULL
        CHECK (purpose IN ('LOGIN', 'PHONE_CHANGE_CURRENT', 'PHONE_CHANGE_NEW', 'DELETE_ACCOUNT')),
    phone             VARCHAR(11) NOT NULL CHECK (phone ~ '^09[0-9]{9}$'),
    "userId"          BIGINT REFERENCES user_tbl ("pId"),
    -- PHONE_CHANGE_CURRENT only: the new phone this code lets the account move to.
    "authorizesPhone" VARCHAR(11) CHECK ("authorizesPhone" ~ '^09[0-9]{9}$'),
    salt              BYTEA       NOT NULL CHECK (length(salt) = 16),
    "codeHash"        BYTEA       NOT NULL CHECK (length("codeHash") = 32),
    "failedAttempts"  SMALLINT    NOT NULL DEFAULT 0 CHECK ("failedAttempts" BETWEEN 0 AND 5),
    "createdOn"       TIMESTAMPTZ NOT NULL,
    "expiresOn"       TIMESTAMPTZ NOT NULL,
    "consumedOn"      TIMESTAMPTZ,
    "replacedOn"      TIMESTAMPTZ,
    -- IPv6 text is at most 45 characters.
    "requestIp"       VARCHAR(45),
    -- Nobody is known yet at login; every other purpose is asked for by a logged-in user.
    CHECK ((purpose = 'LOGIN') = ("userId" IS NULL)),
    CHECK ((purpose = 'PHONE_CHANGE_CURRENT') = ("authorizesPhone" IS NOT NULL)),
    CHECK ("consumedOn" IS NULL OR "replacedOn" IS NULL),
    CHECK ("expiresOn" > "createdOn")
);

-- At most one open code per phone and purpose: sending a new one replaces the open one in the same transaction.
-- Exhausted and expired codes are still open here; the next code sent replaces them.
CREATE UNIQUE INDEX otpchallenge_one_open_idx ON otpchallenge_tbl (phone, purpose)
    WHERE "consumedOn" IS NULL AND "replacedOn" IS NULL;

-- The send limits: one phone's codes of the last day, and all codes of the last hour.
CREATE INDEX otpchallenge_phone_created_idx ON otpchallenge_tbl (phone, "createdOn" DESC);
CREATE INDEX otpchallenge_created_idx ON otpchallenge_tbl ("createdOn");

CREATE TABLE securityevent_tbl
(
    "pId"        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "occurredOn" TIMESTAMPTZ NOT NULL,
    type         VARCHAR(40) NOT NULL CHECK (type ~ '^[A-Z][A-Z0-9_]*$'),
    "userId"     BIGINT,
    phone        VARCHAR(11) CHECK (phone ~ '^09[0-9]{9}$'),
    "sessionId"  BIGINT,
    ip           VARCHAR(45),
    "traceId"    VARCHAR(64),
    detail       JSONB       NOT NULL DEFAULT '{}'
);

CREATE INDEX securityevent_occurred_idx ON securityevent_tbl ("occurredOn");

CREATE FUNCTION securityevent_append_only() RETURNS trigger AS
$$
BEGIN
    RAISE EXCEPTION 'securityevent_tbl is append-only: rows are never changed or removed';
END
$$ LANGUAGE plpgsql;

CREATE TRIGGER securityevent_no_change
    BEFORE UPDATE OR DELETE
    ON securityevent_tbl
    FOR EACH ROW
EXECUTE FUNCTION securityevent_append_only();
