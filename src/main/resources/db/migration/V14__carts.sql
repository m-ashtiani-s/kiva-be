-- Carts (contract /cart): a customer's (one each) or a guest's (reached by a token, of which only the hash is kept).
--
-- Plain tables: a cart changes all the time and its history is worth nothing. A cart keeps no price and no stock of
-- its own; it keeps what the shopper saw last ("seenUnitPrice", "seenPurchasable"), so the next look can say what
-- changed. The CHECKs repeat the rules of the value objects; the limits of stock and per product are the Cart
-- aggregate's, checked against the read model under a lock on the cart's row (SELECT ... FOR UPDATE).

CREATE TABLE cart_tbl
(
    "pId"            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- The contract's Cart.id: random, so it says nothing about how many carts there are.
    "publicId"       VARCHAR(15) NOT NULL UNIQUE CHECK ("publicId" ~ '^cart_[0-9A-Za-z]{10}$'),
    -- A customer has one cart; it goes with the account.
    "userId"         BIGINT UNIQUE REFERENCES user_tbl ("pId") ON DELETE CASCADE,
    -- SHA-256 of a guest's token. The token itself is never stored, so a copy of this table opens no cart.
    "guestTokenHash" BYTEA UNIQUE CHECK (length("guestTokenHash") = 32),
    "shippingMethod" VARCHAR(10) NOT NULL CHECK ("shippingMethod" IN ('TIPAX', 'POST', 'COURIER')),
    reserve          BOOLEAN     NOT NULL,
    -- Round 2 (discount codes, step 20). Upper case, Latin letters and digits, as the code is normalised.
    "discountCode"   VARCHAR(32) CHECK ("discountCode" ~ '^[A-Z0-9-]{2,32}$'),
    "createdOn"      TIMESTAMPTZ NOT NULL,
    -- The last time the cart was used; old guest carts are cleaned up by it (step 16).
    "updatedOn"      TIMESTAMPTZ NOT NULL,
    -- A customer's or a guest's, never both, never neither.
    CONSTRAINT cart_tbl_owner_check CHECK (("userId" IS NULL) <> ("guestTokenHash" IS NULL))
);

-- The cleanup of old guest carts looks only at guests' carts, oldest first.
CREATE INDEX cart_tbl_guest_updated_idx ON cart_tbl ("updatedOn") WHERE "userId" IS NULL;

CREATE TABLE cartitem_tbl
(
    "pId"             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- The contract's CartItem.id. A guest's line keeps it when it moves into the customer's cart after a login.
    "publicId"        VARCHAR(13) NOT NULL UNIQUE CHECK ("publicId" ~ '^ci_[0-9A-Za-z]{10}$'),
    "cartId"          BIGINT      NOT NULL REFERENCES cart_tbl ("pId") ON DELETE CASCADE,
    -- No foreign key to the read model: a table that is written never depends on one that can be rebuilt.
    "variantId"       BIGINT      NOT NULL CHECK ("variantId" > 0),
    quantity          INTEGER     NOT NULL CHECK (quantity BETWEEN 1 AND 20),
    "seenUnitPrice"   BIGINT      NOT NULL CHECK ("seenUnitPrice" >= 0),
    "seenPurchasable" BOOLEAN     NOT NULL,
    "addedOn"         TIMESTAMPTZ NOT NULL,
    -- One line per color; its index is also "the lines of a cart".
    CONSTRAINT cartitem_tbl_cart_variant_key UNIQUE ("cartId", "variantId")
);
