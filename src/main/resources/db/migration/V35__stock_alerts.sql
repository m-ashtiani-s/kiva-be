-- «موجود شد خبرم کن» (completion roadmap, phase 10, section 15.4): a customer waiting for a colour of a product, or for
-- any of its colours ("variantId" NULL), to be back. The SMS goes to the account's phone, read when it is sent: no
-- phone is kept here. No foreign key to the product: the job and the panel read the read model.
--   status ACTIVE until the job tells them once (NOTIFIED, with the colour that came back) or they call it off
--   (CANCELLED); ended rows are deleted after 90 days by the nightly job.
CREATE SEQUENCE stockalertid_seq AS BIGINT START WITH 1;

CREATE TABLE stockalert_tbl
(
    "pId"               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "alertId"           BIGINT      NOT NULL UNIQUE CHECK ("alertId" > 0),
    "userId"            BIGINT      NOT NULL CHECK ("userId" > 0),
    "productId"         BIGINT      NOT NULL CHECK ("productId" > 0),
    "variantId"         BIGINT      CHECK ("variantId" IS NULL OR "variantId" > 0),
    status              VARCHAR(10) NOT NULL CHECK (status IN ('ACTIVE', 'NOTIFIED', 'CANCELLED')),
    "createdOn"         TIMESTAMPTZ NOT NULL,
    "notifiedOn"        TIMESTAMPTZ,
    "notifiedVariantId" BIGINT,
    "cancelledOn"       TIMESTAMPTZ,
    CONSTRAINT stockalert_notified_check CHECK ((status = 'NOTIFIED') = ("notifiedOn" IS NOT NULL AND "notifiedVariantId" IS NOT NULL)),
    CONSTRAINT stockalert_cancelled_check CHECK ((status = 'CANCELLED') = ("cancelledOn" IS NOT NULL))
);
-- One ACTIVE alert per user, product and colour-or-any (decision 4); 0 stands for "any colour".
CREATE UNIQUE INDEX stockalert_one_active_idx ON stockalert_tbl ("userId", "productId", COALESCE("variantId", 0)) WHERE status = 'ACTIVE';
CREATE INDEX stockalert_due_idx ON stockalert_tbl ("productId", "variantId", "createdOn") WHERE status = 'ACTIVE';
CREATE INDEX stockalert_user_idx ON stockalert_tbl ("userId", "createdOn" DESC);
