-- The product read model (QM): what the shop's lists, product pages and filters read. They never read eventstore_tbl.
--
-- Only the projectors write here (ProductQmProjector, InventoryQmProjector), each event right after it is stored and
-- in the same transaction, so these rows always match the events. Nothing else writes here, not even the seeder:
-- data that skipped the events would be lost the day the read model is rebuilt from them.
--
-- Denormalised on purpose: whatever a product card or a filter needs is a column of productqm_tbl, worked out when an
-- event is projected, so a list is one SELECT on one table.
--
-- Column names are camelCase like the Exposed table objects, so every one with a capital letter is quoted.
-- The CHECKs repeat the rules of the value objects; a projector bug stops here instead of reaching the shop.

CREATE TABLE productqm_tbl
(
    "pId"                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "productId"           BIGINT        NOT NULL UNIQUE CHECK ("productId" > 0),
    -- Unique here is the last word on unique slugs and SKUs; the use cases check first to answer 409.
    slug                  VARCHAR(100)  NOT NULL UNIQUE CHECK (slug ~ '^(?=.*[a-z])[a-z0-9]+(-[a-z0-9]+)*$'),
    sku                   VARCHAR(80)   NOT NULL UNIQUE CHECK (sku ~ '^[A-Z][A-Z0-9]*(-[A-Z0-9]+)*$'),
    name                  VARCHAR(120)  NOT NULL CHECK (btrim(name) <> ''),
    -- Name, category, active colors and material through normalizePersian: what the q filter searches.
    "searchText"          TEXT          NOT NULL,
    -- Slugs rather than ids, because the filters arrive as slugs. ON UPDATE CASCADE follows a renamed slug.
    "categorySlug"        VARCHAR(100)  NOT NULL REFERENCES category_tbl (slug) ON UPDATE CASCADE,
    "materialSlug"        VARCHAR(100)  NOT NULL REFERENCES material_tbl (slug) ON UPDATE CASCADE,
    "bagType"             VARCHAR(20)   NOT NULL CHECK ("bagType" IN
                                                        ('HOBO', 'CROSSBODY', 'BACKPACK', 'SATCHEL', 'CLUTCH', 'TOTE', 'BUCKET', 'WALLET')),
    -- The product's own price tag. Colors without one of their own follow it.
    "basePrice"           BIGINT        NOT NULL CHECK ("basePrice" >= 0),
    "baseCompareAtPrice"  BIGINT CHECK ("baseCompareAtPrice" > "basePrice"),
    -- The card's price tag: the default color's (PricePolicy.cardPriceTag). The price filter and sorts use these.
    price                 BIGINT        NOT NULL CHECK (price >= 0),
    "compareAtPrice"      BIGINT CHECK ("compareAtPrice" > price),
    "discountPercent"     INTEGER       NOT NULL CHECK ("discountPercent" BETWEEN 0 AND 100),
    -- The active colors, in display order.
    "colorKeys"           TEXT[]        NOT NULL,
    -- At least one active color can still be sold (on hand minus reserved above zero).
    "inStock"             BOOLEAN       NOT NULL,
    -- At least one active color has a video.
    "hasVideo"            BOOLEAN       NOT NULL,
    -- No event feeds these yet: orders and reviews come in later phases.
    "soldCount"           INTEGER       NOT NULL DEFAULT 0 CHECK ("soldCount" >= 0),
    "ratingAvg"           NUMERIC(2, 1) NOT NULL DEFAULT 0 CHECK ("ratingAvg" BETWEEN 0 AND 5),
    "newUntil"            TIMESTAMPTZ,
    "sortPriority"        INTEGER       NOT NULL,
    "occasions"           TEXT[]        NOT NULL,
    "maxPerOrder"         INTEGER       NOT NULL CHECK ("maxPerOrder" >= 1),
    returnable            BOOLEAN       NOT NULL,
    -- The product page's texts, as the product has them.
    "shortDescription"    VARCHAR(300),
    description           TEXT,
    highlights            TEXT[]        NOT NULL,
    "materialDescription" VARCHAR(120),
    -- Same JSON shape as in the events (ProductSpecsPayload).
    specs                 JSONB         NOT NULL CHECK (jsonb_typeof(specs) = 'object'),
    status                VARCHAR(10)   NOT NULL CHECK (status IN ('DRAFT', 'ACTIVE', 'ARCHIVED')),
    "createdOn"           TIMESTAMPTZ   NOT NULL,
    -- The last change to the product itself; its stock doesn't count.
    "updatedOn"           TIMESTAMPTZ   NOT NULL,
    -- The last time it went into the shop; null while it never has.
    "publishedOn"         TIMESTAMPTZ
);

-- The shop's list is "ACTIVE, maybe one category"; then the sorts; colorKeys answers "has one of these colors" (&&).
CREATE INDEX productqm_tbl_status_category_idx ON productqm_tbl (status, "categorySlug");
CREATE INDEX productqm_tbl_price_idx ON productqm_tbl (price);
CREATE INDEX productqm_tbl_created_on_idx ON productqm_tbl ("createdOn");
CREATE INDEX productqm_tbl_color_keys_idx ON productqm_tbl USING GIN ("colorKeys");

CREATE TABLE productvariantqm_tbl
(
    "pId"            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "variantId"      BIGINT      NOT NULL UNIQUE CHECK ("variantId" > 0),
    "productId"      BIGINT      NOT NULL REFERENCES productqm_tbl ("productId"),
    "colorKey"       VARCHAR(31) NOT NULL REFERENCES color_tbl ("colorKey") ON UPDATE CASCADE,
    sku              VARCHAR(80) NOT NULL UNIQUE CHECK (sku ~ '^[A-Z][A-Z0-9]*(-[A-Z0-9]+)*$'),
    -- What this color costs: its own price tag when hasOwnPrice, otherwise a copy of the product's.
    price            BIGINT      NOT NULL CHECK (price >= 0),
    "compareAtPrice" BIGINT CHECK ("compareAtPrice" > price),
    "hasOwnPrice"    BOOLEAN     NOT NULL,
    "isDefault"      BOOLEAN     NOT NULL,
    "isActive"       BOOLEAN     NOT NULL,
    "sortOrder"      INTEGER     NOT NULL,
    -- The gallery in order, same JSON shape as in the events (ProductMediaPayload).
    media            JSONB       NOT NULL CHECK (jsonb_typeof(media) = 'array'),
    -- The stock, written by InventoryQmProjector. The exact numbers never leave the shop (StockPolicy).
    "onHand"         INTEGER     NOT NULL DEFAULT 0,
    reserved         INTEGER     NOT NULL DEFAULT 0 CHECK (reserved >= 0),

    -- What can be sold (on hand minus reserved) is never negative, as in the Inventory aggregate.
    CONSTRAINT productvariantqm_tbl_available_check CHECK ("onHand" >= reserved),
    -- Only an active color can be the default.
    CONSTRAINT productvariantqm_tbl_default_check CHECK (NOT "isDefault" OR "isActive"),
    -- Each color once per product. Its index also serves "the colors of this product".
    CONSTRAINT productvariantqm_tbl_product_color_key UNIQUE ("productId", "colorKey")
);

-- At most one default color per product. A projector that forgets to take it from the old one stops here.
CREATE UNIQUE INDEX productvariantqm_tbl_one_default_idx ON productvariantqm_tbl ("productId") WHERE "isDefault";
