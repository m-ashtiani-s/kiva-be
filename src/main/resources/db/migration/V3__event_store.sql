-- The event store: every change to an event-sourced aggregate (Product now, Inventory later) is one row here.
-- Rows are only ever added: an aggregate is rebuilt by reading its stream (all rows of one aggregateName +
-- aggregateId) in sequence order. Lists and pages never read this table; they read the QM tables (step 5).
--
-- Column names are camelCase like the Exposed table object, so every one with a capital letter is quoted.
-- The CHECKs repeat the rules of the event value objects (EventAggregateName, EventSequence, ...).

CREATE TABLE eventstore_tbl
(
    "pId"              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "eventId"          UUID         NOT NULL UNIQUE,
    "aggregateName"    VARCHAR(50)  NOT NULL CHECK ("aggregateName" ~ '^[A-Z][A-Z0-9]*(_[A-Z0-9]+)*$'),
    "aggregateId"      VARCHAR(255) NOT NULL CHECK ("aggregateId" <> '' AND btrim("aggregateId") = "aggregateId"),
    sequence           BIGINT       NOT NULL CHECK (sequence >= 1),
    "eventType"        VARCHAR(100) NOT NULL CHECK ("eventType" ~ '^[A-Z][A-Za-z0-9]*$'),
    "payloadVersion"   INTEGER      NOT NULL CHECK ("payloadVersion" >= 1),
    -- The event's own data, written by DomainEventSerializer. JSONB so it can be read with SQL when debugging.
    payload            JSONB        NOT NULL CHECK (jsonb_typeof(payload) = 'object'),
    "occurredOn"       TIMESTAMPTZ  NOT NULL,
    "occurredByUserId" BIGINT       NOT NULL CHECK ("occurredByUserId" >= 0),

    -- One number per event in a stream. When two requests change the same aggregate at once, both try to write
    -- the same next number and this refuses the second: that is what stops one change silently overwriting the other.
    -- Its index also serves reading a stream in order.
    CONSTRAINT eventstore_tbl_stream_sequence_key UNIQUE ("aggregateName", "aggregateId", sequence)
);
