-- Wishlists (completion roadmap, phase 9, section 14.4): the products a customer saved, each with the color they were
-- looking at and its price then; and the public link of a list, at most one per customer.
--
-- wishlistitem_tbl: a row per saved product, at most 200 per customer (the Wishlist aggregate, under the advisory lock
-- wishlist(userId), lock 13). No foreign key to the product: a draft's row stays hidden until it is published again,
-- and archiving a product deletes its rows (ArchiveProductUc). "priceAtAdd" is the sale price when it was first saved.
CREATE TABLE wishlistitem_tbl
(
    "pId"               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "userId"            BIGINT      NOT NULL CHECK ("userId" > 0),
    "productId"         BIGINT      NOT NULL CHECK ("productId" > 0),
    "preferredColorKey" VARCHAR(31) CHECK ("preferredColorKey" ~ '^[a-z][a-z0-9-]{1,30}$'),
    "priceAtAdd"        BIGINT      NOT NULL CHECK ("priceAtAdd" >= 0),
    "addedOn"           TIMESTAMPTZ NOT NULL,
    CONSTRAINT wishlistitem_user_product_key UNIQUE ("userId", "productId")
);
CREATE INDEX wishlistitem_user_idx ON wishlistitem_tbl ("userId", "addedOn" DESC);
CREATE INDEX wishlistitem_product_idx ON wishlistitem_tbl ("productId");

-- wishlistshare_tbl: the live public link of a customer's list; revoking deletes the row, the next share makes a new
-- token. The token is the only secret of the link: wl_ and 32 random base62 characters.
CREATE TABLE wishlistshare_tbl
(
    "pId"       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "userId"    BIGINT      NOT NULL UNIQUE CHECK ("userId" > 0),
    token       VARCHAR(35) NOT NULL UNIQUE CHECK (token ~ '^wl_[0-9A-Za-z]{32}$'),
    "createdOn" TIMESTAMPTZ NOT NULL
);
