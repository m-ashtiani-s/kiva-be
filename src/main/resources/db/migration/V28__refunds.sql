-- Refunds (completion roadmap, phase 2 step 2.6): money to give back to a customer, by hand. The shop only records it:
-- staff transfer the money in their bank's app and record the bank's reference here. No gateway or bank is called, and
-- the IBAN a customer gives on the phone is never stored (roadmap section 1, rows 3 and 4).
--
-- A row per refund, with a version for the optimistic check of each change. No foreign key: a financial record outlives
-- the order's read model and the account. The CHECKs repeat the Refund aggregate's rules; that the refunds of an order
-- never add up to more than it was paid is RefundDomainService's, under the lock of the order's row (lock 9).

CREATE SEQUENCE refundid_seq AS BIGINT START WITH 1;

CREATE TABLE refund_tbl
(
    "pId"          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "refundId"     BIGINT      NOT NULL UNIQUE CHECK ("refundId" > 0),
    "orderId"      BIGINT      NOT NULL CHECK ("orderId" > 0),
    amount         BIGINT      NOT NULL CHECK (amount > 0),
    method         VARCHAR(16) NOT NULL CHECK (method IN ('ORIGINAL_PAYMENT', 'BANK_TRANSFER')),
    status         VARCHAR(10) NOT NULL CHECK (status IN ('PENDING', 'PROCESSING', 'COMPLETED', 'FAILED')),
    source         VARCHAR(16) NOT NULL CHECK (source IN ('MANUAL', 'CANCELLATION', 'CHANGE_REQUEST', 'RETURN')),
    -- Staff's reason; the panel's only.
    reason         VARCHAR(300),
    -- The return it is for (phase 7).
    "returnId"     BIGINT,
    "expectedBy"   TIMESTAMPTZ NOT NULL,
    -- The bank's reference of the transfer: never in a log, nor in the change log.
    "referenceId"  VARCHAR(64) CHECK ("referenceId" ~ '^[0-9A-Za-z-]{1,64}$'),
    -- The note of the last change; the customer sees it.
    "statusNote"   VARCHAR(300),
    "createdOn"    TIMESTAMPTZ NOT NULL,
    "createdBy"    BIGINT      NOT NULL CHECK ("createdBy" >= 0),
    "processingOn" TIMESTAMPTZ,
    "completedOn"  TIMESTAMPTZ,
    "failedOn"     TIMESTAMPTZ,
    version        BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT refund_completed_check CHECK ((status = 'COMPLETED') = ("completedOn" IS NOT NULL)),
    CONSTRAINT refund_failed_check CHECK ((status = 'FAILED') = ("failedOn" IS NOT NULL)),
    CONSTRAINT refund_reference_check CHECK (status <> 'COMPLETED' OR "referenceId" IS NOT NULL)
);

-- An order's refunds, oldest first.
CREATE INDEX refund_order_idx ON refund_tbl ("orderId", "refundId");
-- The panel's queue of refunds to do (refundStatus of GET /admin/orders).
CREATE INDEX refund_open_idx ON refund_tbl (status, "orderId") WHERE status IN ('PENDING', 'PROCESSING');
