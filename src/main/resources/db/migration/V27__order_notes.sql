-- The panel's internal notes on an order (completion roadmap, phase 2 step 2.4): what staff write for each other about
-- an order («مشتری زنگ زد، رنگ مشکی می‌خواد»). Only the panel sees them; they don't change the order, so they are rows of
-- their own and not order events. Append-only: a note is never edited nor removed (a trigger refuses both), so the
-- history of who said what stays as it was.
--
-- No foreign key to the order (orders are events, their read model can be rebuilt) nor to the author (a note outlives
-- the account; the author's name is read from the account when shown).

CREATE TABLE ordernote_tbl
(
    "pId"       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "orderId"   BIGINT        NOT NULL CHECK ("orderId" > 0),
    -- Personal: may say anything about the customer. Never in a log, nor in the change log.
    text        VARCHAR(1000) NOT NULL CHECK (btrim(text) <> ''),
    "authorId"  BIGINT        NOT NULL CHECK ("authorId" > 0),
    "createdOn" TIMESTAMPTZ   NOT NULL
);

-- An order's notes, oldest first.
CREATE INDEX ordernote_order_idx ON ordernote_tbl ("orderId", "createdOn");

CREATE FUNCTION ordernote_append_only() RETURNS trigger AS
$$
BEGIN
    RAISE EXCEPTION 'ordernote_tbl is append-only: notes are never changed or removed';
END
$$ LANGUAGE plpgsql;

CREATE TRIGGER ordernote_no_change
    BEFORE UPDATE OR DELETE
    ON ordernote_tbl
    FOR EACH ROW
EXECUTE FUNCTION ordernote_append_only();
