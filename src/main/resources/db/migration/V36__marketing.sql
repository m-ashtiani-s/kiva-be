-- Marketing and the home page (completion roadmap, phase 11, section 16.4), written whole in the phase's first step
-- (a committed migration is never edited): campaigns, banners, testimonials, and the home page's fixed texts.
-- Plain tables: their history is worth nothing. None of them changes a price (decision 1).

-- Campaigns (جشنواره): a countdown and a list of discounted products, shown while one runs.
--   "productIds" the panel's choice, at most 200; empty: every discounted product in the shop. No foreign key: the
--   shop reads the read model, and a product is never deleted. BIGINT[] as discountcode_tbl's lists.
--   No two active campaigns share a moment (decision 3): the domain checks first, under the advisory lock
--   `campaigns`; the EXCLUDE constraint is the last wall. A range of tstzrange needs no btree_gist.
CREATE SEQUENCE campaignid_seq AS BIGINT START WITH 1;

CREATE TABLE campaign_tbl
(
    "pId"        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "campaignId" BIGINT      NOT NULL UNIQUE CHECK ("campaignId" > 0),
    slug         VARCHAR(60) NOT NULL,
    title        VARCHAR(80) NOT NULL CHECK (btrim(title) <> ''),
    subtitle     VARCHAR(120),
    icon         VARCHAR(30) CHECK (icon ~ '^[a-z0-9-]{1,30}$'),
    "startsAt"   TIMESTAMPTZ NOT NULL,
    "endsAt"     TIMESTAMPTZ NOT NULL,
    "productIds" BIGINT[]    NOT NULL DEFAULT '{}' CHECK (cardinality("productIds") <= 200),
    "isActive"   BOOLEAN     NOT NULL DEFAULT TRUE,
    "createdOn"  TIMESTAMPTZ NOT NULL,
    "updatedOn"  TIMESTAMPTZ NOT NULL,
    CONSTRAINT campaign_tbl_slug_key UNIQUE (slug),
    CONSTRAINT campaign_slug_check CHECK (slug ~ '^(?=.*[a-z])[a-z0-9]+(-[a-z0-9]+)*$'),
    CONSTRAINT campaign_window_check CHECK ("endsAt" > "startsAt"),
    CONSTRAINT campaign_no_overlap EXCLUDE USING gist (tstzrange("startsAt", "endsAt", '[)') WITH &&) WHERE ("isActive")
);

-- Banners of each placement. Shown while "startsAt" <= now < "endsAt" (either NULL is open; decision 7): there is no
-- switch. The image is a media_tbl file (purpose BANNER), never removed once attached. A button has both its label
-- and its link, or neither (decision 8).
CREATE SEQUENCE bannerid_seq AS BIGINT START WITH 1;

CREATE TABLE banner_tbl
(
    "pId"              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "bannerId"         BIGINT      NOT NULL UNIQUE CHECK ("bannerId" > 0),
    placement          VARCHAR(16) NOT NULL CHECK (placement IN ('HOME_HERO', 'HOME_PROMO', 'SHOP_TOP', 'PRODUCT_SIDEBAR', 'BLOG_TOP')),
    theme              VARCHAR(8)  NOT NULL DEFAULT 'CREAM' CHECK (theme IN ('CREAM', 'PURPLE', 'LILAC', 'DARK', 'WHITE')),
    "tagLabel"         VARCHAR(30),
    "tagIcon"          VARCHAR(30) CHECK ("tagIcon" ~ '^[a-z0-9-]{1,30}$'),
    title              VARCHAR(80) NOT NULL CHECK (btrim(title) <> ''),
    text               VARCHAR(200),
    "ctaLabel"         VARCHAR(30),
    "ctaUrl"           VARCHAR(300),
    "imageMediaId"     VARCHAR(26) NOT NULL CHECK ("imageMediaId" ~ '^med_[0-9A-Za-z]{22}$'),
    "overlayHighlight" VARCHAR(30),
    "overlayTitle"     VARCHAR(30),
    "overlaySubtitle"  VARCHAR(30),
    "overlayChannel"   VARCHAR(10) CHECK ("overlayChannel" IN ('RUBIKA', 'TELEGRAM', 'BALE', 'INSTAGRAM')),
    "sortOrder"        INTEGER     NOT NULL DEFAULT 0,
    "startsAt"         TIMESTAMPTZ,
    "endsAt"           TIMESTAMPTZ,
    "createdOn"        TIMESTAMPTZ NOT NULL,
    "updatedOn"        TIMESTAMPTZ NOT NULL,
    CONSTRAINT banner_cta_check CHECK (("ctaLabel" IS NULL) = ("ctaUrl" IS NULL)),
    CONSTRAINT banner_window_check CHECK ("startsAt" IS NULL OR "endsAt" IS NULL OR "endsAt" > "startsAt")
);
CREATE INDEX banner_placement_idx ON banner_tbl (placement, "sortOrder", "bannerId");

-- Testimonials, typed by the panel from a messenger's screenshot. The product is a reference only (no foreign key: the
-- read model keeps every product); the colour follows a renamed colour key (ON UPDATE CASCADE), and a colour with a
-- testimonial can't be removed (409 IN_USE, decision 13).
CREATE SEQUENCE testimonialid_seq AS BIGINT START WITH 1;

CREATE TABLE testimonial_tbl
(
    "pId"               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "testimonialId"     BIGINT       NOT NULL UNIQUE CHECK ("testimonialId" > 0),
    "customerName"      VARCHAR(40)  NOT NULL CHECK (btrim("customerName") <> ''),
    city                VARCHAR(40),
    source              VARCHAR(10)  NOT NULL CHECK (source IN ('RUBIKA', 'TELEGRAM', 'BALE', 'INSTAGRAM')),
    message             VARCHAR(500) NOT NULL CHECK (btrim(message) <> ''),
    "messageTime"       VARCHAR(5)   CHECK ("messageTime" ~ '^\d{2}:\d{2}$'),
    "receivedAt"        TIMESTAMPTZ,
    rating              SMALLINT     NOT NULL DEFAULT 5 CHECK (rating BETWEEN 1 AND 5),
    "productId"         BIGINT       NOT NULL CHECK ("productId" > 0),
    "colorKey"          VARCHAR(31)  REFERENCES color_tbl ("colorKey") ON UPDATE CASCADE,
    "screenshotMediaId" VARCHAR(26)  CHECK ("screenshotMediaId" ~ '^med_[0-9A-Za-z]{22}$'),
    "isPublished"       BOOLEAN      NOT NULL DEFAULT TRUE,
    "sortOrder"         INTEGER      NOT NULL DEFAULT 0,
    "createdOn"         TIMESTAMPTZ  NOT NULL,
    "updatedOn"         TIMESTAMPTZ  NOT NULL
);
CREATE INDEX testimonial_public_idx ON testimonial_tbl ("sortOrder", "receivedAt" DESC NULLS LAST, "testimonialId" DESC) WHERE "isPublished";

