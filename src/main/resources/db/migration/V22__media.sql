-- Uploaded files (completion phase 1, step 1.2, roadmap section 5.2): every photo and video of the shop, whatever it
-- is for (a product, a category, the photos before shipping, a banner, and later the customers' uploads).
--
-- A plain table: a file is never changed after it is stored, so it has no history to keep. The files themselves are on
-- the disk under kiva.media.root, one folder per file ("storageDir"); only paths relative to that root are stored, so
-- the public address can change by configuration alone. A row nothing ever used ("attachedOn" null) is removed with its
-- folder 48 hours after its upload; an attached one never is, since orders' snapshots point at it.
--
-- "uploadedBy" has no foreign key on purpose: the file outlives the account. Nothing has a foreign key to this table
-- either: rows are removed only while nothing uses them.

CREATE TABLE media_tbl
(
    "pId"         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "mediaId"     VARCHAR(26)  NOT NULL UNIQUE CHECK ("mediaId" ~ '^med_[0-9A-Za-z]{22}$'),
    purpose       VARCHAR(20)  NOT NULL CHECK (purpose IN ('PRODUCT', 'PRE_SHIPMENT', 'BLOG', 'BANNER', 'CATEGORY',
                                                          'TESTIMONIAL', 'RETURN_EVIDENCE', 'REVIEW_PHOTO')),
    type          VARCHAR(5)   NOT NULL CHECK (type IN ('IMAGE', 'VIDEO')),
    "mimeType"    VARCHAR(20)  NOT NULL CHECK ("mimeType" IN ('image/webp', 'video/mp4')),
    width         INTEGER      NOT NULL CHECK (width > 0),
    height        INTEGER      NOT NULL CHECK (height > 0),
    "durationSec" INTEGER CHECK ("durationSec" > 0),
    bytes         BIGINT       NOT NULL CHECK (bytes > 0),
    blurhash      VARCHAR(100),
    -- [{width, path}], smallest first: a photo's sizes, or a video's cover frames.
    variants      JSONB        NOT NULL CHECK (jsonb_typeof(variants) = 'array' AND jsonb_array_length(variants) > 0),
    "posterPath"  VARCHAR(200),
    alt           VARCHAR(200) CHECK (alt IS NULL OR length(btrim(alt)) > 0),
    -- "2026/10/med_…", relative to kiva.media.root.
    "storageDir"  VARCHAR(100) NOT NULL CHECK ("storageDir" ~ '^[0-9]{4}/[0-9]{2}/med_[0-9A-Za-z]{22}$'),
    "uploadedBy"  BIGINT       NOT NULL CHECK ("uploadedBy" >= 0),
    "uploadedOn"  TIMESTAMPTZ  NOT NULL,
    "attachedOn"  TIMESTAMPTZ,
    CHECK ((type = 'VIDEO') = ("durationSec" IS NOT NULL)),
    CHECK ((type = 'VIDEO') = ("posterPath" IS NOT NULL)),
    CHECK ((type = 'VIDEO') = ("mimeType" = 'video/mp4'))
);

-- The clean-up job looks only at files nothing uses yet.
CREATE INDEX media_unattached_idx ON media_tbl ("uploadedOn") WHERE "attachedOn" IS NULL;
