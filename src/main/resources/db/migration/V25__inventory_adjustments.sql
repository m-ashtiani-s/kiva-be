-- The stock's history as the panel lists it (phase 1, step 1.8): one row per change made by hand (a delivery, a count,
-- damage, a return, a correction, and a new color's starting stock), with the stock on hand right after it. Orders'
-- reservations, releases and shipments are not here: they are no one's hand change, and a busy color would drown in
-- them. Written by InventoryQmProjector from StockAdjusted, in the same transaction as the event.
--
-- pId        the contract's InventoryAdjustment.id
-- eventId    the StockAdjusted event it comes from (one row per event)
-- stockAfter on hand after this change, computed once here, so the list needs no running sum over the events

CREATE TABLE inventoryadjustmentqm_tbl (
    "pId"              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "eventId"          UUID         NOT NULL UNIQUE,
    "variantId"        BIGINT       NOT NULL,
    "productId"        BIGINT       NOT NULL,
    sku                VARCHAR(80)  NOT NULL,
    delta              INTEGER      NOT NULL CHECK (delta <> 0 AND delta BETWEEN -10000 AND 10000),
    reason             VARCHAR(20)  NOT NULL CHECK (reason IN ('RESTOCK', 'STOCKTAKE', 'DAMAGED', 'RETURNED', 'MANUAL_CORRECTION')),
    note               VARCHAR(300),
    "stockAfter"       INTEGER      NOT NULL CHECK ("stockAfter" >= 0),
    "occurredOn"       TIMESTAMPTZ  NOT NULL,
    "occurredByUserId" BIGINT       NOT NULL CHECK ("occurredByUserId" >= 0)
);

CREATE INDEX inventoryadjustmentqm_variant_idx ON inventoryadjustmentqm_tbl ("variantId", "occurredOn" DESC);
CREATE INDEX inventoryadjustmentqm_occurred_idx ON inventoryadjustmentqm_tbl ("occurredOn" DESC, "pId" DESC);

-- Every adjustment already stored. On hand after each event of a color's stream is the running sum, in sequence order, of
-- what changes it: +delta for StockAdjusted, -quantity for StockShipped (reservations don't move bags). Only the
-- StockAdjusted rows are kept, their product and code from the read model, which has every color.
INSERT INTO inventoryadjustmentqm_tbl ("eventId", "variantId", "productId", sku, delta, reason, note, "stockAfter", "occurredOn", "occurredByUserId")
SELECT s."eventId", v."variantId", v."productId", v.sku, s.delta, s.reason, s.note, s."stockAfter", s."occurredOn", s."occurredByUserId"
  FROM (SELECT e."eventId",
               e."aggregateId"::bigint                       AS "variantId",
               e.sequence,
               e."eventType",
               (e.payload ->> 'delta')::int                  AS delta,
               e.payload ->> 'reason'                        AS reason,
               e.payload ->> 'note'                          AS note,
               e."occurredOn",
               e."occurredByUserId",
               sum(CASE e."eventType"
                       WHEN 'StockAdjusted' THEN (e.payload ->> 'delta')::int
                       WHEN 'StockShipped' THEN -(e.payload ->> 'quantity')::int
                       ELSE 0
                   END) OVER (PARTITION BY e."aggregateId" ORDER BY e.sequence) AS "stockAfter"
          FROM eventstore_tbl e
         WHERE e."aggregateName" = 'INVENTORY') s
  JOIN productvariantqm_tbl v ON v."variantId" = s."variantId"
 WHERE s."eventType" = 'StockAdjusted'
 ORDER BY s."occurredOn", s."variantId", s.sequence;
