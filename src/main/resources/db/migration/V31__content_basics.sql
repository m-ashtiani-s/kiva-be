-- sitecontent_tbl: one row, the texts and links of GET /config that are neither settings nor computed (decision 1),
-- changed with SQL until the panel has a form for them. Read by SiteContentRepositoryImpl, which checks the shape.
-- A text may name a setting as {holdDays}, {returnWindowDays} or {freeShippingThreshold}: GET /config fills it with the
-- setting's value (Persian digits), so changing the setting never leaves a stale number in a text (decision 23).
-- Brand paths starting with "/" are the site's own files: GET /config writes them with the site's address.
-- trustBadges stay empty until the shop has its eNamad and Samandehi codes (launch checklist, step 6.7).
CREATE TABLE sitecontent_tbl
(
    "pId"       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    singleton   BOOLEAN     NOT NULL DEFAULT TRUE UNIQUE CHECK (singleton),
    document    JSONB       NOT NULL CHECK (jsonb_typeof(document) = 'object'),
    "updatedOn" TIMESTAMPTZ NOT NULL
);

