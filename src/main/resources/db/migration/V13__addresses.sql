-- Customers' address books (contract /me/addresses): at most 20 addresses each, exactly one of them the default.
--
-- A plain table: an address is personal data that must be deletable for good, and its history is worth nothing (an
-- order keeps its own copy of the address it was sent to). The CHECKs repeat the rules of the value objects; the
-- limit of 20 and "exactly one default" are kept by the AddressBook aggregate under a lock on the book, and the
-- partial unique index below is the database's own wall against a second default.

-- Address numbers are handed out before the address is saved (AddressIdGenerator), like product ids.
CREATE SEQUENCE addressid_seq;

CREATE TABLE address_tbl
(
    "pId"             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "addressId"       BIGINT       NOT NULL UNIQUE CHECK ("addressId" > 0),
    -- An address means nothing without its customer: it goes with the account.
    "userId"          BIGINT       NOT NULL REFERENCES user_tbl ("pId") ON DELETE CASCADE,
    title             VARCHAR(30) CHECK (btrim(title) <> '' AND title !~ '[[:cntrl:]<>]'),
    "provinceId"      INTEGER      NOT NULL,
    "cityId"          INTEGER      NOT NULL,
    -- Digits stay as the customer typed them; letters and spaces are normalized.
    "addressLine"     VARCHAR(300) NOT NULL CHECK (char_length(btrim("addressLine")) >= 10 AND "addressLine" !~ '[[:cntrl:]<>]'),
    plaque            VARCHAR(10) CHECK (btrim(plaque) <> '' AND plaque !~ '[[:cntrl:]<>]'),
    unit              VARCHAR(10) CHECK (btrim(unit) <> '' AND unit !~ '[[:cntrl:]<>]'),
    "postalCode"      CHAR(10)     NOT NULL CHECK ("postalCode" ~ '^[0-9]{10}$'),
    "recipientName"   VARCHAR(80)  NOT NULL CHECK (char_length(btrim("recipientName")) >= 3 AND "recipientName" !~ '[[:cntrl:]<>]'),
    "recipientPhone"  VARCHAR(11)  NOT NULL CHECK ("recipientPhone" ~ '^09[0-9]{9}$'),
    "isSelfRecipient" BOOLEAN      NOT NULL,
    lat               DOUBLE PRECISION CHECK (lat BETWEEN -90 AND 90),
    lng               DOUBLE PRECISION CHECK (lng BETWEEN -180 AND 180),
    "isDefault"       BOOLEAN      NOT NULL,
    "createdOn"       TIMESTAMPTZ  NOT NULL,
    "updatedOn"       TIMESTAMPTZ  NOT NULL,
    -- A point on the map is both coordinates or none.
    CONSTRAINT address_tbl_location_check CHECK ((lat IS NULL) = (lng IS NULL)),
    -- The city belongs to the province: the pair must be one of city_tbl's (V11).
    CONSTRAINT address_tbl_city_fkey FOREIGN KEY ("provinceId", "cityId") REFERENCES city_tbl ("provinceId", "cityId")
);

-- At most one default per customer; it is also the index of a customer's book.
CREATE UNIQUE INDEX address_one_default_idx ON address_tbl ("userId") WHERE "isDefault";
CREATE INDEX address_tbl_user_idx ON address_tbl ("userId");
