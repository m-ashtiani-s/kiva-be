-- User accounts: the phone they log in with, their profile, their roles.
--
-- A plain table, not event-sourced: personal data must be erasable (deleting an account), and the security history
-- gets its own append-only log. Two edits at the same moment are caught with "version" (optimistic locking): a save
-- updates the row only if it still has the version that was read, and raises it.
--
-- The CHECKs repeat the rules of the value objects (common's IranianMobileNumber, the user's PersonName, Email,
-- BirthDate, Gender, MessengerChannel, Roles); they are the last line of defence against bad data written by hand or
-- by a future bug.

CREATE TABLE user_tbl
(
    "pId"                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- One stored form only, so the same person can't get two accounts by typing their number differently.
    phone                   VARCHAR(11) NOT NULL UNIQUE CHECK (phone ~ '^09[0-9]{9}$'),
    "firstName"             VARCHAR(50) CHECK (btrim("firstName") <> '' AND "firstName" !~ '[[:cntrl:]<>]'),
    "lastName"              VARCHAR(50) CHECK (btrim("lastName") <> '' AND "lastName" !~ '[[:cntrl:]<>]'),
    -- Never verified, so never used to log in.
    email                   VARCHAR(254) CHECK (email ~ '^[a-z0-9._%+-]+@[a-z0-9-]+(\.[a-z0-9-]+)*\.[a-z]{2,}$'),
    "birthDate"             DATE CHECK ("birthDate" >= DATE '1900-01-01'),
    gender                  VARCHAR(11) NOT NULL DEFAULT 'UNSPECIFIED' CHECK (gender IN ('FEMALE', 'MALE', 'UNSPECIFIED')),
    "defaultMessenger"      VARCHAR(10) CHECK ("defaultMessenger" IN ('RUBIKA', 'TELEGRAM', 'BALE')),
    "defaultMessengerPhone" VARCHAR(11) CHECK ("defaultMessengerPhone" ~ '^09[0-9]{9}$'),
    -- Marketing SMS only when the user chooses it themselves.
    "marketingSmsOptIn"     BOOLEAN     NOT NULL DEFAULT FALSE,
    -- CUSTOMER is always there; the rest are the panel roles of the contract's UserRole.
    roles                   TEXT[]      NOT NULL DEFAULT '{CUSTOMER}'
        CHECK ('CUSTOMER' = ANY (roles)
            AND roles <@ ARRAY ['CUSTOMER', 'ADMIN', 'CATALOG_MANAGER', 'OPERATOR', 'CONTENT_EDITOR', 'SUPPORT']),
    "createdOn"             TIMESTAMPTZ NOT NULL,
    version                 BIGINT      NOT NULL DEFAULT 0 CHECK (version >= 0),
    -- A messenger number goes with a messenger.
    CHECK ("defaultMessengerPhone" IS NULL OR "defaultMessenger" IS NOT NULL)
);
