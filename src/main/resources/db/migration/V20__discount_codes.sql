-- Discount codes (purchase step 20, roadmap section 14): the codes, and each order's use of one.
--
-- Plain tables. A code is made by SQL until the panel's discount codes are built (the dev seeder makes three); the shop
-- only reads it. How many times a code was used is never stored: its rows in discountredemption_tbl are counted, HELD
-- and CONFIRMED together, under the code's row lock (SELECT ... FOR UPDATE, section 11 lock 5) when an order is placed,
-- so two orders never take its last use together. The panel's usedCount and totalDiscountGiven are its CONFIRMED rows.

CREATE TABLE discountcode_tbl
(
    "pId"              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Upper case Latin letters, digits, '-' and '_', as the shop normalises what a shopper types (DiscountCodeText).
    code               VARCHAR(32)  NOT NULL UNIQUE CHECK (code ~ '^[A-Z0-9_-]{2,32}$'),
    type               VARCHAR(7)   NOT NULL CHECK (type IN ('PERCENT', 'FIXED')),
    -- A percent (1 to 100), or toman.
    value              INTEGER      NOT NULL CHECK (value > 0),
    label              VARCHAR(200) NOT NULL CHECK (length(btrim(label)) > 0),
    "minSubtotal"      BIGINT CHECK ("minSubtotal" >= 0),
    "maxDiscount"      BIGINT CHECK ("maxDiscount" > 0),
    "startsAt"         TIMESTAMPTZ,
    "endsAt"           TIMESTAMPTZ,
    "usageLimit"       INTEGER CHECK ("usageLimit" > 0),
    "perUserLimit"     INTEGER CHECK ("perUserLimit" > 0),
    "firstOrderOnly"   BOOLEAN      NOT NULL DEFAULT FALSE,
    "requiresLogin"    BOOLEAN      NOT NULL DEFAULT FALSE,
    "excludeSaleItems" BOOLEAN      NOT NULL DEFAULT FALSE,
    -- Only lines of these categories or products; both empty, every line. No foreign keys: a code outlives a category.
    "categoryIds"      BIGINT[]     NOT NULL DEFAULT '{}',
    "productIds"       BIGINT[]     NOT NULL DEFAULT '{}',
    "isActive"         BOOLEAN      NOT NULL DEFAULT TRUE,
    "createdOn"        TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT discountcode_tbl_percent_check CHECK (type <> 'PERCENT' OR value <= 100),
    CONSTRAINT discountcode_tbl_window_check CHECK ("startsAt" IS NULL OR "endsAt" IS NULL OR "endsAt" > "startsAt")
);

CREATE TABLE discountredemption_tbl
(
    "pId"        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- A code with uses is never deleted: switch it off (isActive) instead.
    "codeId"     BIGINT      NOT NULL REFERENCES discountcode_tbl ("pId"),
    -- A financial record, like payment_tbl: no foreign key to the account, it outlives it. No foreign key to the order
    -- either, as orderqm_tbl is a read model.
    "userId"     BIGINT      NOT NULL CHECK ("userId" > 0),
    "orderId"    BIGINT      NOT NULL CHECK ("orderId" > 0),
    -- What the code took off the order, in toman.
    amount       BIGINT      NOT NULL CHECK (amount >= 0),
    status       VARCHAR(9)  NOT NULL CHECK (status IN ('HELD', 'CONFIRMED', 'RELEASED')),
    "heldOn"     TIMESTAMPTZ NOT NULL,
    -- When it was confirmed (the order paid) or released (the order expired).
    "settledOn"  TIMESTAMPTZ,

    -- An order uses a code once, and one code at most.
    CONSTRAINT discountredemption_tbl_code_order_key UNIQUE ("codeId", "orderId"),
    CONSTRAINT discountredemption_tbl_order_key UNIQUE ("orderId"),
    CONSTRAINT discountredemption_tbl_settled_check CHECK ((status = 'HELD') = ("settledOn" IS NULL))
);

-- The uses that count: of a code, and of a code by one customer.
CREATE INDEX discountredemption_code_user_idx ON discountredemption_tbl ("codeId", "userId") WHERE status IN ('HELD', 'CONFIRMED');

-- A cart's code may have '_' too, as the contract's codes do (V14 allowed only '-').
ALTER TABLE cart_tbl DROP CONSTRAINT "cart_tbl_discountCode_check";
ALTER TABLE cart_tbl ADD CONSTRAINT "cart_tbl_discountCode_check" CHECK ("discountCode" ~ '^[A-Z0-9_-]{2,32}$');
