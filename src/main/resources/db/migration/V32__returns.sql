-- Returns (completion roadmap, phase 7, section 12.5): a customer sends lines of a delivered order back; staff approve or
-- turn it down, collect it, check what came and give the money back with a refund of its own (refund_tbl), or close it.
--
-- returnrequest_tbl: a row per return, with a version for the optimistic check of each change (a piece of work with a
-- few steps, not a history: decision 11 of section 1). Its effects on money and stock are in the order's and the stock's
-- events already. No foreign key: the order is an event stream, and a return outlives the order's read model. The CHECKs
-- repeat the ReturnRequest aggregate's rules; the order refuses a second open return first (Order.requestReturn, under
-- the lock of the order's row), and returnrequest_one_per_order_idx is the wall behind it.
--   items       [{lineId, quantity}]: the order's lines going back, each once
--   "mediaIds"  the customer's own RETURN_EVIDENCE uploads, at most 6
--   receipt     {lines: [{lineId, received, restock}], note}: what came back once it was checked; internal
CREATE SEQUENCE returnrequestid_seq AS BIGINT START WITH 1;

CREATE TABLE returnrequest_tbl
(
    "pId"             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "returnId"        BIGINT        NOT NULL UNIQUE CHECK ("returnId" > 0),
    code              VARCHAR(16)   NOT NULL UNIQUE CHECK (code ~ '^RT-[0-9]{4,}$'),
    "orderId"         BIGINT        NOT NULL CHECK ("orderId" > 0),
    "orderCode"       VARCHAR(16)   NOT NULL,
    "userId"          BIGINT        NOT NULL CHECK ("userId" > 0),
    status            VARCHAR(20)   NOT NULL CHECK (status IN ('REQUESTED', 'APPROVED', 'REJECTED', 'PICKUP_SCHEDULED', 'RECEIVED', 'REFUNDED', 'CLOSED')),
    reason            VARCHAR(24)   NOT NULL CHECK (reason IN ('NOT_AS_PICTURED', 'MANUFACTURING_DEFECT', 'WRONG_ITEM', 'DAMAGED_IN_TRANSIT', 'CHANGED_MIND', 'OTHER')),
    -- The customer's words: personal, never logged.
    description       VARCHAR(1000),
    items             JSONB         NOT NULL CHECK (jsonb_typeof(items) = 'array' AND jsonb_array_length(items) BETWEEN 1 AND 20),
    "mediaIds"        JSONB         NOT NULL DEFAULT '[]' CHECK (jsonb_typeof("mediaIds") = 'array' AND jsonb_array_length("mediaIds") <= 6),
    "refundMethod"    VARCHAR(16)   NOT NULL CHECK ("refundMethod" IN ('ORIGINAL_PAYMENT', 'BANK_TRANSFER')),
    "shippingPaidBy"  VARCHAR(8)    NOT NULL CHECK ("shippingPaidBy" IN ('KIVA', 'CUSTOMER')),
    instructions      VARCHAR(1000),
    "rejectionReason" VARCHAR(500),
    "pickupCarrier"   VARCHAR(8) CHECK ("pickupCarrier" IN ('TIPAX', 'POST')),
    "pickupAt"        TIMESTAMPTZ,
    "pickupTracking"  VARCHAR(40) CHECK ("pickupTracking" ~ '^[0-9A-Z-]{6,40}$'),
    "pickupNote"      VARCHAR(500),
    receipt           JSONB CHECK (jsonb_typeof(receipt) = 'object'),
    "closeReason"     VARCHAR(500),
    "refundId"        BIGINT CHECK ("refundId" > 0),
    "createdOn"       TIMESTAMPTZ   NOT NULL,
    "decidedOn"       TIMESTAMPTZ,
    "decidedBy"       BIGINT,
    "receivedOn"      TIMESTAMPTZ,
    "receivedBy"      BIGINT,
    "closedOn"        TIMESTAMPTZ,
    "refundedOn"      TIMESTAMPTZ,
    version           BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT returnrequest_rejected_check CHECK ((status = 'REJECTED') = ("rejectionReason" IS NOT NULL)),
    CONSTRAINT returnrequest_closed_check CHECK ((status = 'CLOSED') = ("closedOn" IS NOT NULL AND "closeReason" IS NOT NULL)),
    CONSTRAINT returnrequest_refunded_check CHECK ((status = 'REFUNDED') = ("refundedOn" IS NOT NULL AND "refundId" IS NOT NULL)),
    CONSTRAINT returnrequest_pickup_check CHECK (status <> 'PICKUP_SCHEDULED' OR "pickupCarrier" IS NOT NULL),
    CONSTRAINT returnrequest_receipt_check CHECK (status NOT IN ('RECEIVED', 'REFUNDED') OR (receipt IS NOT NULL AND "receivedOn" IS NOT NULL)),
    CONSTRAINT returnrequest_decided_check CHECK (status = 'REQUESTED' OR "decidedOn" IS NOT NULL)
);

-- An order's returns («سفارش‌های من» and the panel's order page).
CREATE INDEX returnrequest_order_idx ON returnrequest_tbl ("orderId");
-- «مرجوعی‌های من», newest first.
CREATE INDEX returnrequest_user_idx ON returnrequest_tbl ("userId", "createdOn" DESC);
-- The panel's queue, by status, newest or oldest first.
CREATE INDEX returnrequest_status_idx ON returnrequest_tbl (status, "createdOn");
-- At most one return of an order that isn't REJECTED (decision 1): the domain checks first, this is the second wall.
CREATE UNIQUE INDEX returnrequest_one_per_order_idx ON returnrequest_tbl ("orderId") WHERE status <> 'REJECTED';

-- orderqm_tbl: the order's return (section 12.4). No order had a return before this migration, so the defaults are right
-- for every row there.
--   returnSettled  a return of it was closed or refunded: «مرجوع کردن» never shows again
--   openReturnId   the return being dealt with, while RETURN_REQUESTED or RETURNED
ALTER TABLE orderqm_tbl
    ADD COLUMN "returnSettled" BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN "openReturnId"  BIGINT,
    ADD CONSTRAINT orderqm_open_return_check CHECK (("openReturnId" IS NOT NULL) = (status IN ('RETURN_REQUESTED', 'RETURNED')));

-- refund_tbl: a refund is of a return exactly when its source is RETURN, and a return has at most one refund that isn't
-- FAILED (decision 15: one return, one payment; a failed one is opened again). Safe on the rows there: until now
-- "returnId" was always null and no source was RETURN (phase 2 refused any returnId).
ALTER TABLE refund_tbl
    ADD CONSTRAINT refund_return_source_check CHECK (("returnId" IS NULL) = (source <> 'RETURN'));
CREATE UNIQUE INDEX refund_one_live_per_return_idx ON refund_tbl ("returnId") WHERE "returnId" IS NOT NULL AND status <> 'FAILED';

-- media_tbl: a customer's uploads of the last hour, counted before each upload (phase 7, decision 33).
CREATE INDEX media_uploader_idx ON media_tbl ("uploadedBy", "uploadedOn");
