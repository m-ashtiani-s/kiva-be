-- Payments (purchase step 10): one row per attempt to pay an order, and the log of every exchange with the gateway.
--
-- A plain table, not events: an attempt is the record of a transaction outside the shop, with a short state machine
-- (Payment). Every change locks the row (SELECT ... FOR UPDATE) and checks its version. The gateway is never called
-- inside a transaction; the status says how far an attempt got, so a crash in between can be picked up again.
--
-- A payment is a financial record: it is never deleted, and it outlives the account (account deletion, a later phase,
-- anonymises; it never removes payments). So "userId" has no foreign key, and neither has "orderId": orderqm_tbl is a
-- read model that can be rebuilt. The CHECKs repeat Payment's rules; the unique keys are the last walls against paying
-- twice and against reusing a gateway's session.

CREATE TABLE payment_tbl
(
    "pId"            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- The contract's paymentId: random, so it says nothing about how many payments there are.
    "publicId"       VARCHAR(16)  NOT NULL UNIQUE CHECK ("publicId" ~ '^pay_[0-9A-Z]{12}$'),
    "orderId"        BIGINT       NOT NULL CHECK ("orderId" > 0),
    "userId"         BIGINT       NOT NULL CHECK ("userId" > 0),
    gateway          VARCHAR(10)  NOT NULL CHECK (gateway IN ('ZARINPAL', 'SAMAN', 'MELLAT')),
    -- The order's payable when the attempt was made, in toman: what the gateway is asked for and confirmed with.
    amount           BIGINT       NOT NULL CHECK (amount > 0),
    status           VARCHAR(15)  NOT NULL CHECK (status IN ('INITIATED', 'REDIRECTED', 'START_FAILED', 'CANCELLED', 'VERIFYING',
                                                            'SUCCEEDED', 'FAILED', 'EXPIRED', 'REFUNDED')),
    -- The gateway's id of the session. A callback finds its payment by it.
    authority        VARCHAR(100) CHECK (authority ~ '^[A-Za-z0-9_-]+$'),
    "redirectUrl"    VARCHAR(500) CHECK ("redirectUrl" ~ '^https?://'),
    "redirectMethod" VARCHAR(4) CHECK ("redirectMethod" IN ('GET', 'POST')),
    "redirectFields" JSONB CHECK (jsonb_typeof("redirectFields") = 'object'),
    -- The bank's reference number, once confirmed, and the card as the gateway shows it (never the card's hash).
    "refId"          VARCHAR(64) CHECK ("refId" ~ '^[A-Za-z0-9-]+$'),
    "cardMask"       VARCHAR(32) CHECK ("cardMask" ~ '^[0-9*-]+$'),
    "failureReason"  VARCHAR(30) CHECK ("failureReason" IN ('USER_CANCELLED', 'GATEWAY_DECLINED', 'ORDER_NOT_PAYABLE', 'GATEWAY_UNREACHABLE',
                                                            'GATEWAY_REJECTED', 'EXPIRED')),
    "createdOn"      TIMESTAMPTZ  NOT NULL,
    "redirectedOn"   TIMESTAMPTZ,
    "verifyingSince" TIMESTAMPTZ,
    "settledOn"      TIMESTAMPTZ,
    version          BIGINT       NOT NULL DEFAULT 0,

    -- One session of a gateway is one payment, and one confirmation pays one payment.
    CONSTRAINT payment_tbl_authority_key UNIQUE (gateway, authority),
    CONSTRAINT payment_tbl_ref_key UNIQUE (gateway, "refId"),
    -- From the gateway's session on, its authority and where the shopper goes are known.
    CONSTRAINT payment_tbl_session_check CHECK (status NOT IN ('REDIRECTED', 'VERIFYING', 'SUCCEEDED', 'REFUNDED')
        OR (authority IS NOT NULL AND "redirectUrl" IS NOT NULL)),
    CONSTRAINT payment_tbl_redirect_check CHECK (("redirectUrl" IS NULL) = ("redirectMethod" IS NULL)),
    -- A reference number exactly when confirmed; a reason exactly when it failed.
    CONSTRAINT payment_tbl_ref_check CHECK ((status IN ('SUCCEEDED', 'REFUNDED')) = ("refId" IS NOT NULL)),
    CONSTRAINT payment_tbl_reason_check CHECK ((status IN ('START_FAILED', 'CANCELLED', 'FAILED', 'EXPIRED')) = ("failureReason" IS NOT NULL)),
    CONSTRAINT payment_tbl_settled_check CHECK ((status IN ('INITIATED', 'REDIRECTED', 'VERIFYING')) = ("settledOn" IS NULL))
);

-- The last wall against taking an order's money twice: two attempts that both came back paid can't both be confirmed.
CREATE UNIQUE INDEX payment_one_success_per_order_idx ON payment_tbl ("orderId") WHERE status IN ('SUCCEEDED', 'REFUNDED');

-- An order's attempts, the latest first (the order's page, the retry limit).
CREATE INDEX payment_order_created_idx ON payment_tbl ("orderId", "createdOn" DESC);

-- The reconciliation job looks only at attempts not settled yet.
CREATE INDEX payment_unsettled_idx ON payment_tbl (status) WHERE status IN ('REDIRECTED', 'VERIFYING');

-- Every exchange with a gateway, for support: codes and numbers only, never the gateway's raw answer. Only added to.
CREATE TABLE paymentlog_tbl
(
    "pId"         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "paymentId"   BIGINT      NOT NULL REFERENCES payment_tbl ("pId"),
    "occurredOn"  TIMESTAMPTZ NOT NULL,
    kind          VARCHAR(10) NOT NULL CHECK (kind IN ('REQUEST', 'CALLBACK', 'VERIFY', 'INQUIRY', 'REVERSE')),
    outcome       VARCHAR(30) NOT NULL CHECK (outcome ~ '^[A-Z][A-Z0-9_]*$'),
    "gatewayCode" INTEGER,
    "httpStatus"  INTEGER CHECK ("httpStatus" BETWEEN 100 AND 599),
    "durationMs"  INTEGER CHECK ("durationMs" >= 0)
);

CREATE INDEX paymentlog_payment_idx ON paymentlog_tbl ("paymentId", "occurredOn");

-- The same wall as securityevent_tbl: a row of the log is never changed or removed, by anyone.
CREATE FUNCTION paymentlog_append_only() RETURNS trigger AS
$$
BEGIN
    RAISE EXCEPTION 'paymentlog_tbl is append-only: rows are never changed or removed';
END
$$ LANGUAGE plpgsql;

CREATE TRIGGER paymentlog_no_change
    BEFORE UPDATE OR DELETE
    ON paymentlog_tbl
    FOR EACH ROW
EXECUTE FUNCTION paymentlog_append_only();
