-- Reviews (completion roadmap, phase 8, section 13.4): a customer's stars and words about a product, approved by support
-- before the shop shows them, maybe with Kiva's reply; who found which helpful; and each product's rating.
--
-- review_tbl: a row per review, with a version for the optimistic check of each change (a record, not a history:
-- decision 11 of section 1). No foreign key to the product or the order: a review outlives a product taken off the
-- read model's lists, and the order is an event stream. The CHECKs repeat the Review aggregate's rules; at most one live
-- review (PENDING or APPROVED) per user and product: ReviewDomainService checks first, review_one_live_idx is the wall.
--   text, "replyText", "rejectionReason", contact   personal: never logged
--   "orderId", "orderCode", "lineId", "color…"        the delivered line it is linked to (the badge «خریدار»), or none
--   "mediaIds"                                        the customer's own REVIEW_PHOTO uploads, at most 5
CREATE SEQUENCE reviewid_seq AS BIGINT START WITH 1;

CREATE TABLE review_tbl
(
    "pId"             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "reviewId"        BIGINT        NOT NULL UNIQUE CHECK ("reviewId" > 0),
    "productId"       BIGINT        NOT NULL CHECK ("productId" > 0),
    "userId"          BIGINT        NOT NULL CHECK ("userId" > 0),
    rating            SMALLINT      NOT NULL CHECK (rating BETWEEN 1 AND 5),
    "authorName"      VARCHAR(40)   CHECK ("authorName" IS NULL OR btrim("authorName") <> ''),
    contact           VARCHAR(100)  CHECK (contact IS NULL OR contact ~ '^09[0-9]{9}$' OR contact ~ '^[a-z0-9._%+-]+@[a-z0-9-]+(\.[a-z0-9-]+)*\.[a-z]{2,}$'),
    text              VARCHAR(1000) NOT NULL CHECK (char_length(btrim(text)) >= 10),
    status            VARCHAR(8)    NOT NULL CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    "rejectionReason" VARCHAR(300)  CHECK ("rejectionReason" IS NULL OR char_length(btrim("rejectionReason")) >= 3),
    "orderId"         BIGINT,
    "orderCode"       VARCHAR(16)   CHECK ("orderCode" IS NULL OR "orderCode" ~ '^KV-[0-9]{6}$'),
    "lineId"          INTEGER       CHECK ("lineId" IS NULL OR "lineId" >= 1),
    "colorKey"        VARCHAR(40),
    "colorName"       VARCHAR(40),
    "colorHex"        VARCHAR(7),
    "mediaIds"        JSONB         NOT NULL DEFAULT '[]' CHECK (jsonb_typeof("mediaIds") = 'array' AND jsonb_array_length("mediaIds") <= 5),
    "helpfulCount"    INTEGER       NOT NULL DEFAULT 0 CHECK ("helpfulCount" >= 0),
    "replyText"       VARCHAR(1000) CHECK ("replyText" IS NULL OR char_length(btrim("replyText")) >= 2),
    "repliedOn"       TIMESTAMPTZ,
    "repliedBy"       BIGINT,
    "createdOn"       TIMESTAMPTZ   NOT NULL,
    "updatedOn"       TIMESTAMPTZ   NOT NULL,
    "moderatedOn"     TIMESTAMPTZ,
    "moderatedBy"     BIGINT,
    version           BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT review_rejected_reason_check CHECK ((status = 'REJECTED') = ("rejectionReason" IS NOT NULL)),
    CONSTRAINT review_purchase_check CHECK (
        ("orderId" IS NULL) = ("lineId" IS NULL) AND ("orderId" IS NULL) = ("orderCode" IS NULL)
            AND ("orderId" IS NULL) = ("colorKey" IS NULL) AND ("orderId" IS NULL) = ("colorName" IS NULL) AND ("orderId" IS NULL) = ("colorHex" IS NULL)),
    CONSTRAINT review_reply_check CHECK (("replyText" IS NULL) = ("repliedOn" IS NULL) AND ("replyText" IS NULL) = ("repliedBy" IS NULL)),
    CONSTRAINT review_moderated_check CHECK (status = 'PENDING' OR "moderatedOn" IS NOT NULL)
);
-- one live review per user and product (decision 2); the domain checks first
CREATE UNIQUE INDEX review_one_live_idx ON review_tbl ("userId", "productId") WHERE status IN ('PENDING', 'APPROVED');
CREATE INDEX review_public_idx ON review_tbl ("productId", "createdOn" DESC) WHERE status = 'APPROVED';
CREATE INDEX review_user_idx ON review_tbl ("userId", "createdOn" DESC);
CREATE INDEX review_queue_idx ON review_tbl (status, "createdOn" DESC);

-- reviewvote_tbl: who found which review helpful; goes with its review.
CREATE TABLE reviewvote_tbl
(
    "reviewId"  BIGINT      NOT NULL REFERENCES review_tbl ("reviewId") ON DELETE CASCADE,
    "userId"    BIGINT      NOT NULL CHECK ("userId" > 0),
    "createdOn" TIMESTAMPTZ NOT NULL,
    PRIMARY KEY ("reviewId", "userId")
);
CREATE INDEX reviewvote_user_idx ON reviewvote_tbl ("userId");

-- productrating_tbl: each product's rating over its APPROVED reviews (decision 15), apart from the product's read model,
-- which only the product's projector writes. Changed by the review use cases (RatingBook) under the row's lock. The CHECKs
-- keep the numbers agreeing: a use case that forgot to take a review out can't leave a rating that doesn't add up.
CREATE TABLE productrating_tbl
(
    "productId"     BIGINT      PRIMARY KEY CHECK ("productId" > 0),
    count           INTEGER     NOT NULL DEFAULT 0 CHECK (count >= 0),
    sum             INTEGER     NOT NULL DEFAULT 0 CHECK (sum >= 0),
    stars1          INTEGER     NOT NULL DEFAULT 0 CHECK (stars1 >= 0),
    stars2          INTEGER     NOT NULL DEFAULT 0 CHECK (stars2 >= 0),
    stars3          INTEGER     NOT NULL DEFAULT 0 CHECK (stars3 >= 0),
    stars4          INTEGER     NOT NULL DEFAULT 0 CHECK (stars4 >= 0),
    stars5          INTEGER     NOT NULL DEFAULT 0 CHECK (stars5 >= 0),
    "verifiedCount" INTEGER     NOT NULL DEFAULT 0 CHECK ("verifiedCount" >= 0),
    "updatedOn"     TIMESTAMPTZ NOT NULL,
    CONSTRAINT productrating_count_check CHECK (count = stars1 + stars2 + stars3 + stars4 + stars5),
    CONSTRAINT productrating_sum_check CHECK (sum = stars1 + 2 * stars2 + 3 * stars3 + 4 * stars4 + 5 * stars5),
    CONSTRAINT productrating_verified_check CHECK ("verifiedCount" <= count)
);
CREATE INDEX productrating_sort_idx ON productrating_tbl (((sum::numeric / NULLIF(count, 0))) DESC NULLS LAST, count DESC);

