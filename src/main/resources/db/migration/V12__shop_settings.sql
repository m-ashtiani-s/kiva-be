-- The shop's settings: shipping methods and their costs, free shipping, payment gateways, and the deadlines of payment
-- and reservation. In the database rather than application.conf because the admin panel (contract AdminSettings) will
-- edit them, and a change must take effect without a restart: the application reads them on every request.
--
-- Starting values from the design (kiva.js, checkout.html) and the contract. COURIER (پیک) has no row yet: the design
-- has no name, cost or delivery time for it, and a method without a row is simply not offered.
-- The delivery text («تحویل ۳ تا ۵ روز کاری») is not stored: the HTTP layer builds it from minDays and maxDays,
-- so it can never disagree with them.

CREATE TABLE shippingmethod_tbl
(
    "pId"       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(10) NOT NULL UNIQUE CHECK (code IN ('TIPAX', 'POST', 'COURIER')),
    name        VARCHAR(50) NOT NULL CHECK (btrim(name) <> ''),
    -- In toman, before any free shipping.
    "baseCost"  BIGINT      NOT NULL CHECK ("baseCost" >= 0),
    -- Working days from the day of shipping; Fridays and the other non-shipping days don't count.
    "minDays"   INTEGER     NOT NULL CHECK ("minDays" >= 0),
    "maxDays"   INTEGER     NOT NULL CHECK ("maxDays" <= 30),
    -- An icon of the frontend's set (contract IconName).
    icon        VARCHAR(30) NOT NULL CHECK (btrim(icon) <> ''),
    "isActive"  BOOLEAN     NOT NULL,
    "sortOrder" INTEGER     NOT NULL,
    CONSTRAINT shippingmethod_tbl_days_check CHECK ("minDays" <= "maxDays")
);

CREATE TABLE paymentgateway_tbl
(
    "pId"        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code         VARCHAR(10)  NOT NULL UNIQUE CHECK (code IN ('ZARINPAL', 'SAMAN', 'MELLAT')),
    name         VARCHAR(50)  NOT NULL CHECK (btrim(name) <> ''),
    -- The logo's stand-in when there is no logoUrl: one letter on the brand color.
    "brandColor" VARCHAR(7)   NOT NULL CHECK ("brandColor" ~ '^#[0-9A-Fa-f]{6}$'),
    initial      VARCHAR(1)   NOT NULL CHECK (btrim(initial) <> ''),
    "logoUrl"    VARCHAR(500),
    -- Switched on by the shop. A gateway is offered only when it is active AND the application has an adapter for it.
    "isActive"   BOOLEAN      NOT NULL,
    "isDefault"  BOOLEAN      NOT NULL,
    "sortOrder"  INTEGER      NOT NULL,
    CONSTRAINT paymentgateway_tbl_default_active_check CHECK (NOT "isDefault" OR "isActive")
);

-- At most one default gateway.
CREATE UNIQUE INDEX paymentgateway_one_default_idx ON paymentgateway_tbl ((TRUE)) WHERE "isDefault";

CREATE TABLE shopsettings_tbl
(
    "pId"                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Exactly one row: the column can only be TRUE, and only once.
    singleton               BOOLEAN     NOT NULL DEFAULT TRUE UNIQUE CHECK (singleton),
    -- In toman, compared with the subtotal (after product discounts, before a discount code).
    "freeShippingThreshold" BIGINT      NOT NULL CHECK ("freeShippingThreshold" >= 0),
    "freeShippingMethods"   TEXT[]      NOT NULL CHECK ("freeShippingMethods" <@ ARRAY ['TIPAX', 'POST', 'COURIER']),
    -- A new cart's method.
    "defaultShippingMethod" VARCHAR(10) NOT NULL REFERENCES shippingmethod_tbl (code),
    -- java.time.DayOfWeek names; at least one day of the week must be left for shipping.
    "nonShippingWeekdays"   TEXT[]      NOT NULL CHECK ("nonShippingWeekdays" <@ ARRAY ['MONDAY', 'TUESDAY', 'WEDNESDAY', 'THURSDAY',
                                                                                         'FRIDAY', 'SATURDAY', 'SUNDAY']
                                                    AND cardinality("nonShippingWeekdays") < 7),
    -- How long a placed order holds its stock while it waits for payment.
    "paymentPendingMinutes" INTEGER     NOT NULL CHECK ("paymentPendingMinutes" BETWEEN 5 AND 60),
    "reservationEnabled"    BOOLEAN     NOT NULL,
    "reservationHoldDays"   INTEGER     NOT NULL CHECK ("reservationHoldDays" BETWEEN 1 AND 14),
    "returnWindowDays"      INTEGER     NOT NULL CHECK ("returnWindowDays" BETWEEN 0 AND 60),
    "updatedOn"             TIMESTAMPTZ NOT NULL,
    -- For the admin panel's edits later (optimistic locking).
    version                 BIGINT      NOT NULL DEFAULT 0
);

