-- Orders (purchase step 9): the sequence their ids come from, and their read model.
--
-- An order is event-sourced: its truth is its stream in eventstore_tbl (ORDER/{orderId}). orderqm_tbl is what the
-- customer's lists and pages, the jobs and the panel read instead; they never read the event store. Only
-- OrderQmProjector writes here, each event right after it is stored and in the same transaction, so a row always
-- matches its events; and it can be rebuilt from them. So it has no foreign key: a write table never depends on one
-- that can be rebuilt, and an order outlives anything it points to.
--
-- Columns for what is filtered or sorted on (owner, status, times); JSONB for what is only shown, in the same shapes as
-- the OrderPlaced event (OrderLinePayload, AddressSnapshotPayload, ...). The CHECKs repeat the aggregate's rules: a
-- projector bug stops here instead of reaching a customer.

-- An order has no row before its first event, so OrderIdGeneratorImpl takes its id from here. Its public code
-- (KV-218340) is made from the id (OrderCodePolicy); gaps from rolled-back orders only skip codes.
CREATE SEQUENCE orderid_seq AS BIGINT START WITH 1;

CREATE TABLE orderqm_tbl
(
    "pId"              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "orderId"          BIGINT      NOT NULL UNIQUE CHECK ("orderId" > 0),
    -- OrderCodePolicy makes every code its own; this is the second wall.
    code               VARCHAR(11) NOT NULL UNIQUE CHECK (code ~ '^KV-[0-9]{4,8}$'),
    "userId"           BIGINT      NOT NULL CHECK ("userId" > 0),
    status             VARCHAR(20) NOT NULL CHECK (status IN ('PENDING_PAYMENT', 'PAYMENT_FAILED', 'EXPIRED', 'RESERVED', 'PROCESSING',
                                                              'PHOTO_SENT', 'CHANGE_REQUESTED', 'SHIPPED', 'DELIVERED', 'CANCELLED',
                                                              'RETURN_REQUESTED', 'RETURNED', 'REFUNDED')),
    "placedOn"         TIMESTAMPTZ NOT NULL,
    "paidOn"           TIMESTAMPTZ,
    -- The end of the time to pay and of the stock hold. Never moved.
    "holdUntil"        TIMESTAMPTZ NOT NULL CHECK ("holdUntil" > "placedOn"),
    payable            BIGINT      NOT NULL CHECK (payable >= 0),
    "itemsCount"       INTEGER     NOT NULL CHECK ("itemsCount" >= 1),
    "shippingMethod"   VARCHAR(10) NOT NULL CHECK ("shippingMethod" IN ('TIPAX', 'POST', 'COURIER')),
    "messengerChannel" VARCHAR(10) NOT NULL CHECK ("messengerChannel" IN ('RUBIKA', 'TELEGRAM', 'BALE')),
    -- «رزرو ۴ روزه» asked for (round 2).
    "reserveRequested" BOOLEAN     NOT NULL,
    lines              JSONB       NOT NULL CHECK (jsonb_typeof(lines) = 'array' AND jsonb_array_length(lines) >= 1),
    -- Personal data (address, phones, notes): shown to the customer and the panel, never logged.
    address            JSONB       NOT NULL CHECK (jsonb_typeof(address) = 'object'),
    messenger          JSONB       NOT NULL CHECK (jsonb_typeof(messenger) = 'object'),
    totals             JSONB       NOT NULL CHECK (jsonb_typeof(totals) = 'object'),
    -- One entry per event (status, time, a failed attempt's reason): OrderDetail.timeline, oldest first.
    timeline           JSONB       NOT NULL CHECK (jsonb_typeof(timeline) = 'array' AND jsonb_array_length(timeline) >= 1),
    gift               JSONB CHECK (jsonb_typeof(gift) = 'object'),
    "customerNote"     VARCHAR(300),
    -- The time of its last event.
    "updatedOn"        TIMESTAMPTZ NOT NULL,
    -- Paid exactly when the money came in.
    CONSTRAINT orderqm_tbl_paid_check CHECK ((status IN ('PENDING_PAYMENT', 'PAYMENT_FAILED', 'EXPIRED')) = ("paidOn" IS NULL))
);

-- The expiry job looks only at unpaid orders, by the end of their time to pay.
CREATE INDEX orderqm_unpaid_hold_idx ON orderqm_tbl ("holdUntil") WHERE status IN ('PENDING_PAYMENT', 'PAYMENT_FAILED');

-- «سفارش‌های من»: one customer's orders, newest first.
CREATE INDEX orderqm_user_placed_idx ON orderqm_tbl ("userId", "placedOn" DESC);
